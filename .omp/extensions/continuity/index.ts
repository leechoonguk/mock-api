/**
 * Continuity — the two jobs, and nothing else.
 *
 * 이 확장의 원래 컨셉은 둘이었다: 로컬 모델의 **방향을 유지**하고, 컨텍스트가 나빠지면 **초기화**한다.
 * 그 사이 루프 감지·골 카드·수용 판정·리포트·프로파일이 붙어 4,083줄이 됐고, 실측은 그 대부분이
 * 비용만 냈다고 말한다(전수 부검):
 *
 * - 개입은 `pi.sendMessage(..., {deliverAs:"steer"})` 로 나가 **직전 턴이 큐에 넣은 도구 호출을 취소**했다.
 *   코퍼스 전체에서 취소 2,266건(95/190 세션), 셀당 20~34건, 벽시계의 15~40%.
 * - rung-1 증거의 1,075건이 `identical call 3x` 인데, 취소된 호출이 그대로 재발행되며 만들어진 것이다.
 *   즉 루프 감지기가 자기 피해를 루프로 읽었다.
 * - 골 카드는 사용자 역할 메시지를 목표로 캡처해, 실제 상태 파일의 goal 이 우리 WRITE-STEER 문구로
 *   덮여 있었다 — "방향 유지"의 정반대다.
 * - `continuity_goal` 도구·수용 판정은 190 세션에서 **0회** 호출됐고, 압축 복구는 0회 발화,
 *   `recordUsage` 텔레메트리는 러너 필터와 어긋나 101개 행 전부 null 이었다.
 *
 * 2차 축소: 하이진 컷도 뺐다. 짝 비교(rest 6셀, 상한 ON/OFF ×3)에서 컷이 있는 팔은
 * 자체 종료 0/3·게이트 초록 0/3, 없는 팔은 1/3·1/3 이었고 회귀는 6셀 모두 0 — 컷이 필요하다는
 * 근거가 하나도 없었다. 원래 근거(ctx 45k→22k, 턴 12~120초→3.5~17초)는 개입이 셀당 20~34건의
 * 도구 호출을 취소하며 컨텍스트를 부풀리던 옛 하네스의 수치였다. 컨텍스트 관리는 omp 소관이다.
 *
 * 남은 것은 `discipline.ts` 의 둘뿐이다: REG-WATCH(배선 유실 방어)와 마감 게이트(가짜 완료 방어).
 * 둘 다 omp 가 알 수 없는 **프로젝트 고유 계약**이다. 메시지는 전부 `pi.sendUserMessage` 로만
 * 나가고, 확장은 문맥을 만지지 않는다.
 */

import { registerDiscipline } from "./discipline.ts";

export default function continuity(pi: unknown): void {
  registerDiscipline(pi as never);
}
