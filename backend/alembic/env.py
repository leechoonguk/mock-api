import asyncio
from logging.config import fileConfig

from sqlalchemy import Column
from sqlalchemy.ext.asyncio import async_engine_from_config
from sqlalchemy.pool import NullPool
from sqlalchemy.types import JSON

from alembic import context
from app.core.settings import settings
from app.models.base import Base
from app.models.endpoint import Endpoint  # noqa: F401 — on metadata
from app.models.project import Project  # noqa: F401 — on metadata
from app.models.request_log import RequestLog  # noqa: F401 — on metadata


config = context.config

# Use DATABASE_URL from Settings/env, not alembic.ini.
config.set_main_option("sqlalchemy.url", settings.database_url)

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = Base.metadata


def _compare_server_default(
    context: object,
    inspected_column: object,
    metadata_column: Column[object],
    inspected_default: object,
    metadata_default: object,
    rendered_metadata_default: object,
) -> bool | None:
    """Whether a server default differs, skipping JSON columns.

    A JSON default is declared once and never edited, and comparing one asks
    the database to compare JSON values, which not every dialect can; every
    other column goes through the normal comparison.
    """
    if isinstance(metadata_column.type, JSON):
        return False
    return None


def run_migrations_online() -> None:
    """Run migrations in 'online' mode with async engine."""
    connectable = async_engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=NullPool,
    )

    async def _run() -> None:
        async with connectable.connect() as connection:
            await connection.run_sync(do_run_migrations)

    asyncio.run(_run())


def do_run_migrations(connection) -> None:  # type: ignore[no-untyped-def]
    # One transaction per migration, not one for the whole run: a multi-step run
    # that fails stops at the last revision that fully applied, so the version
    # pointer and the rows still agree.
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        transaction_per_migration=True,
        # SQLite cannot ALTER most of a table in place: batch mode rebuilds the
        # table (create, copy, drop, rename) so autogenerated column and
        # constraint changes apply on SQLite at all.
        render_as_batch=True,
        # A column's server default is part of the schema, and autogenerate
        # ignores it unless asked.
        compare_server_default=_compare_server_default,
    )
    with context.begin_transaction():
        context.run_migrations()


run_migrations_online()
